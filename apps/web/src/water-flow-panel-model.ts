export function waterFlowFramesFromCommand(
  command: WaterFlowCommandEnvelope | null | undefined,
): readonly WaterFlowFrameView[] | null {
  const frames = command?.waterFlow;
  return Array.isArray(frames) ? frames : null;
}

function isWaterFlowFrame(value: unknown): value is WaterFlowFrameView {
  if (!value || typeof value !== 'object') return false;
  const frame = value as Partial<WaterFlowFrameView>;
  if (typeof frame.bounds !== 'object' || frame.bounds === null) return false;
  if (typeof frame.provenance !== 'object' || frame.provenance === null) return false;
  return (
    frame.flowVersion === 'omega.water-flow.v1' &&
    typeof frame.stage === 'string' &&
    KNOWN_STAGES.has(frame.stage) &&
    typeof frame.sequence === 'number' &&
    Number.isInteger(frame.sequence) &&
    typeof frame.state === 'string' &&
    typeof frame.transition === 'string' &&
    typeof frame.traceId === 'string' &&
    frame.deterministic === true &&
    Number.isInteger(frame.bounds.maxSteps) &&
    frame.bounds.maxSteps >= 1 &&
    frame.bounds.maxSteps <= WATER_FLOW_STAGES.length &&
    frame.sequence >= 0 &&
    frame.sequence < frame.bounds.maxSteps &&
    typeof frame.provenance.source === 'string' &&
    typeof frame.provenance.verified === 'boolean' &&
    typeof frame.provenance.note === 'string'
  );
}

/**
 * Accept only a complete, ordered v1 local trace. A rejected payload remains
 * visible as DIVERGENT at the UI boundary; it is never normalized into proof.
 */
export type TraceOnlyPipelineReceiptResult =
  | { readonly ok: true; readonly frames: WaterFlowFrameView[] }
  | { readonly ok: false; readonly reason: 'INVALID_RESPONSE' | 'EXECUTION_BOUNDARY_NOT_CONFIRMED' | 'WATER_FLOW_DIVERGENT' };

/** Accept only the intentionally denied, non-executing pipeline trace response. */
export function normalizeTraceOnlyPipelineReceipt(input: unknown): TraceOnlyPipelineReceiptResult {
  if (!input || typeof input !== 'object') return { ok: false, reason: 'INVALID_RESPONSE' };
  const response = input as { success?: unknown; pipeline?: unknown };
  if (response.success !== true || !response.pipeline || typeof response.pipeline !== 'object') {
    return { ok: false, reason: 'INVALID_RESPONSE' };
  }

  const pipeline = response.pipeline as Record<string, unknown>;
  const executionBoundaryConfirmed =
    pipeline.stage === 'ADMIT' &&
    pipeline.halted === true &&
    pipeline.haltReason === 'DENIED' &&
    pipeline.decision === 'DENY' &&
    pipeline.executionStatus === null &&
    pipeline.attestationId === null &&
    pipeline.realityStatus === null &&
    pipeline.realityAttestation === null;

  if (!executionBoundaryConfirmed) return { ok: false, reason: 'EXECUTION_BOUNDARY_NOT_CONFIRMED' };
  const frames = normalizeWaterFlowFrames(pipeline.waterFlow);
  return frames
    ? { ok: true, frames }
    : { ok: false, reason: 'WATER_FLOW_DIVERGENT' };
}

export function normalizeWaterFlowFrames(input: unknown): WaterFlowFrameView[] | null {
  if (!Array.isArray(input) || input.length === 0 || input.length > WATER_FLOW_STAGES.length) return null;
  if (!input.every(isWaterFlowFrame)) return null;

  const frames = input as WaterFlowFrameView[];
  const first = frames[0];
  const expectedMaxSteps = first.bounds.maxSteps;
  const expectedTraceId = first.traceId;

  if (frames.length !== expectedMaxSteps || expectedMaxSteps !== frames.length) return null;
  if (expectedMaxSteps < 1 || expectedMaxSteps > WATER_FLOW_STAGES.length) return null;
  if (!expectedTraceId.trim()) return null;

  for (let index = 0; index < frames.length; index += 1) {
    const frame = frames[index];
    if (frame.sequence !== index) return null;
    if (frame.stage !== WATER_FLOW_STAGES[index]) return null;
    if (frame.traceId !== expectedTraceId) return null;
    if (frame.bounds.maxSteps !== expectedMaxSteps) return null;
    if (frame.provenance.source !== 'local-water-flow' || frame.provenance.verified !== false) return null;
  }

  return frames;
}

function livingWaterSteps(
  stages: readonly WaterFlowStage[],
  hasFrames: boolean,
  traceStatus: WaterFlowStatus,
): readonly LivingWaterStepView[] {
  return LIVING_WATER_BINDINGS.map((binding) => {
    let status: LivingWaterStageStatus;
    if (!hasFrames) status = 'NOT_EXECUTED';
    else if (traceStatus === 'DIVERGENT') status = 'DIVERGENT';
    else if (binding.machineStages.some((stage) => stages.includes(stage))) status = 'MODEL_ONLY';
    else status = 'UNKNOWN';

    return { ...binding, status };
  });
}

export function summarizeWaterFlow(frames: readonly WaterFlowFrameView[] | null | undefined): WaterFlowSummary {
  if (!frames || frames.length === 0) {
    return {
      status: 'NOT_EXECUTED',
      stages: [],
      traceId: null,
      maxSteps: 0,
      note: 'No active command receipt supplied; no Living Water step is claimed as executed.',
      livingWaterSteps: livingWaterSteps([], false, 'NOT_EXECUTED'),
    };
  }

  const validFrames = frames.filter(isWaterFlowFrame);
  const first = validFrames[0];
  const stages = validFrames.map((frame) => frame.stage);
  const contractMatches =
    validFrames.length === frames.length &&
    validFrames.length > 0 &&
    validFrames.every((frame) => frame.provenance.source === 'local-water-flow' && frame.provenance.verified === false);
  const status: WaterFlowStatus = contractMatches ? 'UNKNOWN' : 'DIVERGENT';

  return {
    status,
    stages,
    traceId: first?.traceId ?? null,
    maxSteps: first?.bounds.maxSteps ?? 0,
    note: contractMatches
      ? 'The v1 frames are deterministic local representations. A mapped stage is MODEL_ONLY, not proof of execution, observation, or verification; unmapped steps remain UNKNOWN.'
      : 'Frame shape or provenance diverges from the bounded local-water-flow contract; reconcile before relying on this trace.',
    livingWaterSteps: livingWaterSteps(stages, true, status),
  };
}
